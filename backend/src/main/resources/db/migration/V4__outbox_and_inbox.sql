CREATE TABLE cae_outbox_event (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  event_id VARCHAR(64) NOT NULL,
  logical_event_id VARCHAR(64) NOT NULL,
  aggregate_id BIGINT NOT NULL,
  event_type VARCHAR(64) NOT NULL,
  payload JSON NOT NULL,
  exchange_name VARCHAR(128) NOT NULL,
  routing_key VARCHAR(128) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'NEW',
  retry_count INT NOT NULL DEFAULT 0,
  delivery_attempt INT NOT NULL DEFAULT 0,
  next_retry_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  claim_owner VARCHAR(64) NULL,
  claim_until DATETIME(6) NULL,
  last_error VARCHAR(1000) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  published_at DATETIME(6) NULL,
  UNIQUE KEY uk_outbox_event_id(event_id),
  KEY idx_outbox_due(status,next_retry_time,id),
  KEY idx_outbox_expired_claim(status,claim_until,id),
  KEY idx_outbox_aggregate(aggregate_id,id),
  KEY idx_outbox_logical(logical_event_id,id),
  CONSTRAINT fk_outbox_job FOREIGN KEY(aggregate_id) REFERENCES cae_job(id)
);

CREATE TABLE cae_message_inbox (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  logical_event_id VARCHAR(64) NOT NULL,
  consumer_name VARCHAR(64) NOT NULL,
  job_id BIGINT NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'NEW',
  retry_count INT NOT NULL DEFAULT 0,
  claim_owner VARCHAR(64) NULL,
  claim_until DATETIME(6) NULL,
  next_retry_time DATETIME(6) NULL,
  last_delivery_id VARCHAR(64) NOT NULL,
  last_error VARCHAR(1000) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  completed_at DATETIME(6) NULL,
  UNIQUE KEY uk_inbox_logical_consumer(logical_event_id,consumer_name),
  KEY idx_inbox_recovery(status,claim_until),
  CONSTRAINT fk_inbox_job FOREIGN KEY(job_id) REFERENCES cae_job(id)
);
