CREATE TABLE cae_result_parse_record (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  job_id BIGINT NOT NULL,
  execution_id BIGINT NOT NULL,
  parser_version VARCHAR(32) NOT NULL,
  raw_checksum VARCHAR(64) NOT NULL,
  analysis_type VARCHAR(24) NOT NULL,
  condition_code VARCHAR(64) NOT NULL,
  subcase INT NOT NULL,
  maturity VARCHAR(24) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'REQUESTED',
  metric_count INT NOT NULL DEFAULT 0,
  failure_message VARCHAR(1000),
  post_requested_at DATETIME(6),
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  completed_at DATETIME(6),
  UNIQUE KEY uk_parse_job_version(job_id,parser_version),
  KEY idx_parse_execution(execution_id),
  FOREIGN KEY(job_id) REFERENCES cae_job(id),
  FOREIGN KEY(execution_id) REFERENCES cae_job_execution(id),
  CHECK(subcase BETWEEN 1 AND 1000)
);
CREATE TABLE result_metric (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  parse_record_id BIGINT NOT NULL,
  job_id BIGINT NOT NULL,
  execution_id BIGINT NOT NULL,
  parser_version VARCHAR(32) NOT NULL,
  metric_code VARCHAR(64) NOT NULL,
  metric_name VARCHAR(160) NOT NULL,
  value_num DECIMAL(30,10),
  value_text VARCHAR(500),
  unit VARCHAR(64) NOT NULL,
  dimension VARCHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL,
  condition_code VARCHAR(64) NOT NULL,
  subcase INT NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uk_metric_job_version_code(job_id,parser_version,metric_code),
  KEY idx_metric_parse(parse_record_id),
  FOREIGN KEY(parse_record_id) REFERENCES cae_result_parse_record(id),
  FOREIGN KEY(job_id) REFERENCES cae_job(id),
  FOREIGN KEY(execution_id) REFERENCES cae_job_execution(id),
  CHECK((value_num IS NULL) <> (value_text IS NULL))
);
CREATE TABLE cae_artifact (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  job_id BIGINT NOT NULL,
  execution_id BIGINT NOT NULL,
  parse_record_id BIGINT,
  parser_version VARCHAR(32) NOT NULL DEFAULT '',
  stage_version INT NOT NULL DEFAULT 0,
  artifact_type VARCHAR(32) NOT NULL,
  uri VARCHAR(500) NOT NULL,
  file_name VARCHAR(160) NOT NULL,
  size_bytes BIGINT NOT NULL,
  checksum VARCHAR(64) NOT NULL,
  content_type VARCHAR(160) NOT NULL,
  metadata JSON NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uk_artifact_job_uri(job_id,uri),
  KEY idx_artifact_job_type(job_id,artifact_type),
  KEY idx_artifact_parse(parse_record_id),
  FOREIGN KEY(job_id) REFERENCES cae_job(id),
  FOREIGN KEY(execution_id) REFERENCES cae_job_execution(id),
  FOREIGN KEY(parse_record_id) REFERENCES cae_result_parse_record(id),
  CHECK(size_bytes>=0),
  CHECK(stage_version>=0)
);
